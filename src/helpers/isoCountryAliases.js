/**
 * ISO 3166-1 alpha-2 → aliases for matching Countries.name (Russian) in DB.
 * All world countries/territories (+ XK). Russian names from ISO 3166 ru locale.
 */

const normalize = (str = '') => str
  .toString()
  .toLowerCase()
  .normalize('NFD')
  .replace(/[\u0300-\u036f]/g, '')
  .replace(/\s+/g, ' ')
  .trim();

