/** UK is not ISO official; some APIs use it instead of GB */
ISO_COUNTRY_ALIASES.UK = ISO_COUNTRY_ALIASES.GB;

/**
 * @param {Array<{ _id: unknown, name?: string }>} countries
 * @param {string} isoCode
 * @returns {typeof countries[number] | null}
 */
export const findCountryByIso = (countries, isoCode = '') => {
  const iso = String(isoCode || '').toUpperCase();
  const aliases = ISO_COUNTRY_ALIASES[iso];
  if (!aliases?.length) return null;
  return countries.find((c) => {
    const name = normalize(c.name);
    return aliases.some((alias) => {
      const a = normalize(alias);
      return name === a || name.includes(a) || a.includes(name);
    });
  }) || null;
};

/**
 * ISO-коды Ticketmaster, для которых страна есть в DB (матч через ISO_COUNTRY_ALIASES).
 * @param {Array<{ _id: unknown, name?: string }>} countries
 * @param {string[]} ticketmasterCountryCodes
 */
export const getTicketmasterCountriesInDb = (
  countries,
  ticketmasterCountryCodes,
) => ticketmasterCountryCodes.filter((iso) => findCountryByIso(countries, iso));

/**
 * @param {object} meta
 * @param {Array<{ _id: unknown, name?: string }>} countries
 * @param {string[]} ticketmasterCountryCodes
 */
export const resolveTicketmasterCountryCodes = (
  meta = {},
  countries = [],
  ticketmasterCountryCodes = [],
) => {
  if (meta.countryCode) return [String(meta.countryCode).toUpperCase()];
  if (Array.isArray(meta.countryCodes) && meta.countryCodes.length) {
    return meta.countryCodes.map((code) => String(code).toUpperCase());
  }
  return getTicketmasterCountriesInDb(countries, ticketmasterCountryCodes);
};

